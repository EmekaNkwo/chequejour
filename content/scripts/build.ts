/**
 * Compiles content/source into content/build/content.json and writes the audio
 * manifest (a static require() map, which Metro needs to bundle the clips).
 * Fails on any validation error.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { collectAudioClips } from '../../domain/audio-keys';
import { AUDIO_DIR, AUDIO_EXT, loadAll, ROOT, summarize, type Report } from './load';

const BUILD_DIR = join(ROOT, 'content', 'build');

const report: Report = { errors: [], warnings: [] };
const bundle = loadAll(report);
for (const w of report.warnings) process.stdout.write(`warn  ${w}\n`);
if (report.errors.length > 0) {
  for (const e of report.errors) process.stdout.write(`ERROR ${e}\n`);
  process.stdout.write(`Build failed: ${report.errors.length} error(s).\n`);
  process.exit(1);
}

mkdirSync(BUILD_DIR, { recursive: true });
writeFileSync(join(BUILD_DIR, 'content.json'), JSON.stringify(bundle));

const keys = [...new Set(collectAudioClips(bundle).map((c) => c.key))]
  .filter((key) => existsSync(join(AUDIO_DIR, `${key}${AUDIO_EXT}`)))
  .sort();
const manifest = [
  '// Generated by content/scripts/build.ts — do not edit.',
  '/* eslint-disable */',
  'export const AUDIO_CLIPS: Readonly<Record<string, number>> = {',
  ...keys.map((k) => `  '${k}': require('../../assets/audio/${k}${AUDIO_EXT}'),`),
  '};',
  '',
].join('\n');
writeFileSync(join(BUILD_DIR, 'audio-manifest.ts'), manifest);

process.stdout.write(`${summarize(bundle)}\naudio clips bundled: ${keys.length}\nBuilt content/build/content.json\n`);
